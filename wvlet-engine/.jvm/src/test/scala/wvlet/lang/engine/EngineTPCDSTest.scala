package wvlet.lang.engine

import wvlet.uni.test.UniTest

import java.nio.file.Files
import java.nio.file.Paths
import java.nio.file.StandardCopyOption
import java.sql.DriverManager

/**
  * TPC-DS queries, in Wvlet (spec/tpcds) and SQL (spec/sql/tpc-ds), on the engine must return the
  * same rows as DuckDB. Both sides read the same Parquet files generated by DuckDB's tpcds
  * extension
  */
class EngineTPCDSTest extends UniTest:

  /**
    * Query numbers the engine does not support yet (the same in both spec sets). This list must
    * only shrink
    */
  private val knownGaps: Set[Int] = Set()

  private val (dataDir, tables) = EngineTPCDSTest.prepareData(EngineTPCDSTest.scaleFactor)

  private def newConformance(specPath: String) = EngineConformance(
    specPath,
    tables.map(t => s"create view ${t} as select * from '${dataDir}/${t}.parquet'"),
    engine => tables.foreach(t => engine.catalog.registerParquet(t, s"${dataDir}/${t}.parquet"))
  )

  private val wv  = newConformance("spec/tpcds")
  private val sql = newConformance("spec/sql/tpc-ds")

  override def afterAll: Unit =
    wv.close()
    sql.close()

  private def queryNumber(fileName: String): Int = fileName.filter(_.isDigit).toInt

  for
    (label, c) <- Seq("wv" -> wv, "sql" -> sql)
    unit       <- c.units
  do
    val fileName = unit.sourceFile.fileName
    test(s"${label}:${fileName}") {
      if knownGaps.contains(queryNumber(fileName)) then
        ignore("Not supported in the engine yet")
      c.run(unit)
        .foreach { r =>
          debug(s"${r.name}: ${r.message}")
          if !r.matched then
            fail(s"${r.name}: ${r.message}")
          if r.message.startsWith("skipped") then
            fail(s"${r.name}: DuckDB rejected the query: ${r.message}")
        }
    }

end EngineTPCDSTest

object EngineTPCDSTest:
  val scaleFactor: Double = 0.1

  /** Generate TPC-DS Parquet files with DuckDB's tpcds extension, once per scale factor */
  def prepareData(sf: Double): (String, Seq[String]) =
    val dir    = Paths.get(s"target/tpcds-sf${sf}").toAbsolutePath
    val done   = dir.resolve("_tables")
    val tables =
      if Files.exists(done) then
        String(Files.readAllBytes(done)).split("\n").toSeq
      else
        Files.createDirectories(dir)
        Class.forName("org.duckdb.DuckDBDriver")
        val conn = DriverManager.getConnection("jdbc:duckdb:")
        try
          val st = conn.createStatement()
          try
            st.execute("install tpcds")
            st.execute("load tpcds")
            st.execute(s"call dsdgen(sf = ${sf})")
            val rs = st.executeQuery("show tables")
            val ts = Seq.newBuilder[String]
            while rs.next() do
              ts += rs.getString(1)
            val names = ts.result()
            names.foreach { t =>
              val tmp = dir.resolve(s"${t}.parquet.tmp")
              st.execute(s"copy ${t} to '${tmp}' (format parquet)")
              Files.move(tmp, dir.resolve(s"${t}.parquet"), StandardCopyOption.REPLACE_EXISTING)
            }
            Files.write(done, names.mkString("\n").getBytes)
            names
          finally
            st.close()
        finally
          conn.close()
    (dir.toString, tables)

  end prepareData

end EngineTPCDSTest
