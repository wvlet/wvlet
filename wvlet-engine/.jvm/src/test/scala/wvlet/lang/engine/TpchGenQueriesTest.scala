package wvlet.lang.engine

import wvlet.lang.compiler.CompilationUnit
import wvlet.lang.compiler.Compiler
import wvlet.lang.compiler.CompilerOptions
import wvlet.lang.compiler.DBType
import wvlet.lang.compiler.WorkEnv
import wvlet.lang.compiler.codegen.GenSQL
import wvlet.lang.engine.catalog.TpchGen
import wvlet.uni.test.UniTest

import java.io.File

/** Every spec/tpch query runs on the engine over tables generated by [[TpchGen]] */
class TpchGenQueriesTest extends UniTest:
  private val engine = WvletEngine()
  private val tables = TpchGen.register(engine.catalog, 0.01)

  // A typed catalog, so stdlib methods on columns (q13's o_comment.like) resolve
  private val compiler = Compiler(
    CompilerOptions(sourceFolders = Nil, workEnv = WorkEnv("."), dbType = DBType.Wvlet)
  )

  compiler.setDefaultCatalog(wvlet.lang.engine.catalog.EngineCatalog.toCompileCatalog(tables))
  compiler.setDefaultSchema(wvlet.lang.engine.catalog.EngineCatalog.SchemaName)

  private val queries = File("spec/tpch")
    .listFiles()
    .filter(f => f.getName.matches("q[0-9]+(-opt)?\\.wv"))
    .sortBy(_.getName)

  queries.foreach { f =>
    test(s"should run TPC-H ${f.getName} on generated tables") {
      val unit = CompilationUnit.fromFile(f.getPath)
      val r    = compiler.compileSingleUnit(unit)
      r.reportAllErrors
      given ctx: wvlet.lang.compiler.Context = r.context
      val q                                  = EngineTPCHBench.queryOf(unit).get
      val res                                = engine.execute(GenSQL.expand(q, ctx))
      debug(s"${f.getName}: ${res.numRows} rows")
      res.schema.size > 0 shouldBe true
    }
  }

  test("should return rows for the queries whose filters the generated values satisfy") {
    // Queries with a selective filter on generated text may legitimately return no rows at a
    // small scale; these must not
    Seq("q1.wv", "q3.wv", "q5.wv", "q6.wv", "q10.wv", "q12.wv", "q13.wv", "q14.wv", "q18.wv")
      .foreach { name =>
        val unit                               = CompilationUnit.fromFile(s"spec/tpch/${name}")
        val r                                  = compiler.compileSingleUnit(unit)
        given ctx: wvlet.lang.compiler.Context = r.context
        val res = engine.execute(GenSQL.expand(EngineTPCHBench.queryOf(unit).get, ctx))
        if name != "q18.wv" then
          (name, res.numRows > 0) shouldBe (name, true)
      }
  }

  test("should run TPC-H q1 at SF 1 by generating line items while scanning") {
    val e = WvletEngine()
    TpchGen.register(e.catalog, 1.0)
    val unit                               = CompilationUnit.fromFile("spec/tpch/q1.wv")
    val r                                  = compiler.compileSingleUnit(unit)
    given ctx: wvlet.lang.compiler.Context = r.context
    val start                              = System.nanoTime()
    val res = e.execute(GenSQL.expand(EngineTPCHBench.queryOf(unit).get, ctx))
    debug(f"q1 at SF 1: ${(System.nanoTime() - start) / 1e9}%.1f s")
    res.numRows shouldBe 4
  }

end TpchGenQueriesTest
