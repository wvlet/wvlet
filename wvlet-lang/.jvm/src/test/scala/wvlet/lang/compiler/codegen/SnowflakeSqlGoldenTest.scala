/**
  * The Snowflake SQL generated for the standard-library specs (spec/basic/stdlib_*.wv) must match
  * the golden files under spec/snowflake-sql. CI has no Snowflake account, so this pins the SQL of
  * the `in snowflake` variants and shows any change in the PR diff; whether Snowflake accepts it is
  * checked locally with SnowflakeStdLibSpec (see design/testing.md). Regenerate the files with
  * [[SnowflakeSqlGolden.regenCommand]]
  */
class SnowflakeSqlGoldenTest extends UniTest:
  import SnowflakeSqlGolden.*

  test("Snowflake SQL of the stdlib specs matches spec/snowflake-sql") {
    val generated = generate()
    val existing  =
      if Files.isDirectory(goldenDir) then
        sqlFiles(goldenDir).map(_.getFileName.toString).toSet
      else
        Set.empty[String]
    val drift = Seq.newBuilder[String]
    generated.foreach { (file, sql) =>
      val path = goldenDir.resolve(file)
      if !Files.exists(path) then
        drift += s"missing: ${path}"
      else
        val golden = String(Files.readAllBytes(path))
        if golden != sql then
          val g    = golden.linesIterator.toIndexedSeq
          val s    = sql.linesIterator.toIndexedSeq
          val line = g.zipAll(s, "<missing line>", "<missing line>").indexWhere(_ != _)
          drift += s"""changed: ${path} (line ${line + 1})
               |  golden   : ${g.lift(line).getOrElse("<missing line>")}
               |  generated: ${s.lift(line).getOrElse("<missing line>")}""".stripMargin
    }
    (existing -- generated.keySet).foreach(f => drift += s"stale: ${goldenDir.resolve(f)}")
    val d = drift.result()
    if d.nonEmpty then
      fail(
        s"""Snowflake SQL changed for ${d.size} stdlib spec file(s):
           |${d.take(10).mkString("\n")}
           |If the changes are intended, regenerate the golden files with:
           |  ${regenCommand}
           |and check the changed SQL on Snowflake with SnowflakeStdLibSpec (see design/testing.md)"""
          .stripMargin
      )
  }

end SnowflakeSqlGoldenTest

/**
  * Writes the golden Snowflake SQL of the stdlib specs: `./sbt "langJVM/Test/runMain ..."` (see
  * [[regenCommand]])
  */
object SnowflakeSqlGolden:
  val regenCommand: String =
    """./sbt "langJVM/Test/runMain wvlet.lang.compiler.codegen.SnowflakeSqlGolden""""

  private val specDir: Path  = Paths.get("spec/basic")
  val goldenDir: Path        = Paths.get("spec/snowflake-sql")
  private val header: String = "-- Generated by SnowflakeSqlGolden from spec/basic/"
  private val regenNote      = s"-- Regenerate with: ${regenCommand}"

  /** The stdlib spec files that run on every engine with stdlib variants */
  def specFiles: Seq[Path] = Files
    .list(specDir)
    .iterator()
    .asScala
    .filter { p =>
      val name = p.getFileName.toString
      name.startsWith("stdlib_") && name.endsWith(".wv")
    }
    .toSeq
    .sortBy(_.getFileName.toString)

  def sqlFiles(dir: Path): Seq[Path] =
    Files.list(dir).iterator().asScala.filter(_.getFileName.toString.endsWith(".sql")).toSeq

  /**
    * The golden file name and content for each stdlib spec. A spec that does not compile for
    * Snowflake (e.g. a function with no Snowflake variant) records the error message instead, so
    * that adding a variant also shows up in the diff
    */
  def generate(): Map[String, String] =
    specFiles
      .map { spec =>
        val name = spec.getFileName.toString
        val body =
          try
            generateSQL(spec)
          catch
            case e: WvletLangException =>
              s"-- compile error: ${e.statusCode}: ${e
                  .getMessage
                  .linesIterator
                  .nextOption()
                  .getOrElse("")}"
        name.stripSuffix(".wv") + ".sql" -> s"${header}${name}\n${regenNote}\n${body.trim}\n"
      }
      .toMap

  private def generateSQL(spec: Path): String =
    // Compile each spec alone: spec/basic files compiled together can see each other's vals
    val compiler = Compiler(CompilerOptions(workEnv = WorkEnv("."), dbType = DBType.Snowflake))
    val unit     = CompilationUnit.fromFile(spec.toString)
    val result   = compiler.compileSingleUnit(unit)
    result.reportAllErrors
    // Drop the per-statement version comment, which changes with every commit
    GenSQL
      .generateSQL(unit)(using result.context)
      .linesIterator
      .filterNot(_.startsWith("-- wvlet version="))
      .mkString("\n")

  def main(args: Array[String]): Unit =
    Files.createDirectories(goldenDir)
    sqlFiles(goldenDir).foreach(Files.delete)
    val files = generate()
    files.foreach { (file, sql) =>
      Files.writeString(goldenDir.resolve(file), sql)
    }
    println(s"Wrote ${files.size} files to ${goldenDir}")

end SnowflakeSqlGolden
